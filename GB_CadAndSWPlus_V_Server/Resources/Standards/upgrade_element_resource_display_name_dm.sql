-- 为已有达梦 ELEMENT_RESOURCES 资源表增加 SolidWorks 模型按键显示名。
-- 可重复执行；不会修改 ELEMENT_DEFINITIONS.DISPLAY_NAME 或现有资源数据。
DECLARE
	V_COUNT INT;
BEGIN
	SELECT COUNT(1) INTO V_COUNT
	FROM ALL_TABLES
	WHERE OWNER = 'CAD_SW_LIBRARY' AND TABLE_NAME = 'ELEMENT_RESOURCES';

	IF V_COUNT > 0 THEN
		SELECT COUNT(1) INTO V_COUNT
		FROM ALL_TAB_COLUMNS
		WHERE OWNER = 'CAD_SW_LIBRARY'
		  AND TABLE_NAME = 'ELEMENT_RESOURCES'
		  AND COLUMN_NAME = 'DISPLAY_NAME';

		IF V_COUNT = 0 THEN
			EXECUTE IMMEDIATE 'ALTER TABLE CAD_SW_LIBRARY.ELEMENT_RESOURCES ADD DISPLAY_NAME VARCHAR(255)';
		END IF;
	END IF;
END;
/

SELECT OWNER, TABLE_NAME, COLUMN_NAME, DATA_TYPE, NULLABLE
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'CAD_SW_LIBRARY'
  AND TABLE_NAME = 'ELEMENT_RESOURCES'
  AND COLUMN_NAME = 'DISPLAY_NAME';
